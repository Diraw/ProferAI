/**
 * agent-session-title-naming.test.ts —— 共享自动命名窗口的行为契约（旧链与新链同一实现）
 *
 * 这里只驱动**共享模块**（两端注入替身），因此不启动 Electron、不读真实会话文件、不调模型：
 * - 生成器用替身（返回指定标题 / 返回 null / 抛错）；
 * - 转录与元数据都在内存里；
 * - 覆盖「何时生成 / 生成几次 / 何时锁定 / 失败不阻断 / 不覆盖用户改名 / 寒暄不烧次数」。
 *
 * 与 `title-generation.test.ts` 的分工：那份测纯判据（`planTitleWindow` / `collectTitleSources`），
 * 这份测会话级编排（读转录、写元数据、投影标题事件）。
 */

import { describe, expect, test } from 'bun:test'
import type { AgentGenerateTitleInput, AgentSessionMeta, SDKMessage } from '@profer/shared'
import {
  collectSessionTitleSources,
  runSessionTitleNaming,
  type SessionTitleNamingLogger,
  type SessionTitleNamingPorts,
} from './agent-session-title-naming'
import { DEFAULT_SESSION_TITLE } from './agent-prompt-utils'
import { TITLE_LOCK_MIN_SOURCES, TITLE_REFINE_MAX_ATTEMPTS, TITLE_SOURCE_MAX_COUNT } from './title-generation'

const USER_MESSAGE = '帮我比较 grok 和 gpt 在长上下文上的差异'
const SECOND_MESSAGE = '再补充一份工具调用上的对比表格'

function userMessage(text: string): SDKMessage {
  return {
    type: 'user',
    message: { content: [{ type: 'text', text }] },
    parent_tool_use_id: null,
  } as unknown as SDKMessage
}

function assistantMessage(text: string): SDKMessage {
  return {
    type: 'assistant',
    message: { content: [{ type: 'text', text }] },
    parent_tool_use_id: null,
  } as unknown as SDKMessage
}

function freshMeta(overrides: Partial<AgentSessionMeta> = {}): AgentSessionMeta {
  return {
    id: 'title-session',
    title: DEFAULT_SESSION_TITLE,
    agentRuntime: 'pi',
    createdAt: 1,
    updatedAt: 1,
    ...overrides,
  }
}

interface NamingHarness {
  ports: SessionTitleNamingPorts
  /** 每次 updateMeta 的补丁（按顺序）。 */
  writes: Array<Partial<AgentSessionMeta>>,
  /** 每次生成调用的入参。 */
  generations: AgentGenerateTitleInput[]
  /** `onTitleUpdated` 收到的标题（按顺序）。 */
  projected: string[]
  /** 当前会话元数据（会被 updateMeta 写回）。 */
  meta: () => AgentSessionMeta
  /** 覆盖元数据（模拟生成期间用户改名 / 外部定稿）。 */
  setMeta(patch: Partial<AgentSessionMeta>): void
  logs: string[]
  warns: string[]
}

function createHarness(options: {
  meta?: AgentSessionMeta
  messages?: readonly SDKMessage[]
  generate?: (input: AgentGenerateTitleInput) => Promise<string | null>
  readMessagesThrows?: boolean
  userMessage?: string
} = {}): NamingHarness {
  let meta = options.meta ?? freshMeta()
  const writes: Array<Partial<AgentSessionMeta>> = []
  const generations: AgentGenerateTitleInput[] = []
  const projected: string[] = []
  const logs: string[] = []
  const warns: string[] = []
  const log: SessionTitleNamingLogger = {
    log: (message) => { logs.push(message) },
    warn: (message) => { warns.push(message) },
  }

  const ports: SessionTitleNamingPorts = {
    sessionId: meta.id,
    userMessage: options.userMessage ?? USER_MESSAGE,
    channelId: 'fixture-channel',
    modelId: 'fixture-model',
    defaultTitle: DEFAULT_SESSION_TITLE,
    getMeta: () => meta,
    updateMeta: (_sessionId, patch) => {
      writes.push(patch)
      meta = { ...meta, ...patch }
    },
    readMessages: () => {
      if (options.readMessagesThrows) throw new Error('transcript read failed')
      return options.messages ?? [userMessage(options.userMessage ?? USER_MESSAGE)]
    },
    generate: async (input) => {
      generations.push(input)
      if (options.generate) return await options.generate(input)
      return `生成标题·${generations.length}`
    },
    onTitleUpdated: title => { projected.push(title) },
    logTag: '[test]',
    log,
  }

  return {
    ports,
    writes,
    generations,
    projected,
    meta: () => meta,
    setMeta: (patch) => { meta = { ...meta, ...patch } },
    logs,
    warns,
  }
}

describe('自动命名窗口：何时生成 / 何时锁定', () => {
  test('首条有效来源：生成一次并写入临时标题（来源 < 2 时不定稿）', async () => {
    const h = createHarness()
    await expect(runSessionTitleNaming(h.ports)).resolves.toBe(true)

    expect(h.generations).toEqual([{
      userMessage: USER_MESSAGE,
      channelId: 'fixture-channel',
      modelId: 'fixture-model',
      contextMessages: [USER_MESSAGE],
    }])
    // 尝试次数先预占，再应用标题；未达定稿门槛不写 titleLockedAt。
    expect(h.writes).toEqual([
      { titleRefineAttempts: 1 },
      { title: '生成标题·1', titleAutoGeneratedAt: expect.any(Number) },
    ])
    expect(h.projected).toEqual(['生成标题·1'])
    expect(h.meta().titleLockedAt).toBeUndefined()
  })

  test('第二条有效来源：精修并定稿（写入 titleLockedAt）', async () => {
    const h = createHarness({
      messages: [userMessage(USER_MESSAGE), assistantMessage('好的'), userMessage(SECOND_MESSAGE)],
      meta: freshMeta({ title: '临时标题', titleAutoGeneratedAt: 1, titleRefineAttempts: 1 }),
    })
    await expect(runSessionTitleNaming(h.ports)).resolves.toBe(true)

    expect(h.generations[0]?.contextMessages).toEqual([USER_MESSAGE, SECOND_MESSAGE])
    // 窗口用最早一条来源作为 `userMessage`（与旧链一致）。
    expect(h.generations[0]?.userMessage).toBe(USER_MESSAGE)
    expect(h.writes[0]).toEqual({ titleRefineAttempts: 2 })
    expect(h.writes[1]).toMatchObject({ title: '生成标题·1', titleAutoGeneratedAt: expect.any(Number), titleLockedAt: expect.any(Number) })
    expect(h.projected).toEqual(['生成标题·1'])
    expect(TITLE_LOCK_MIN_SOURCES).toBe(2)
  })

  test('已定稿：预判阶段直接返回，不读转录、不生成、不写盘', async () => {
    const h = createHarness({
      meta: freshMeta({ title: '已定稿', titleAutoGeneratedAt: 1, titleLockedAt: 2 }),
      readMessagesThrows: true,
    })
    await expect(runSessionTitleNaming(h.ports)).resolves.toBe(false)
    expect(h.generations).toEqual([])
    expect(h.writes).toEqual([])
    expect(h.projected).toEqual([])
  })

  test('人工命名：关闭窗口并写 titleLockedAt（永不覆盖用户决定）', async () => {
    const h = createHarness({ meta: freshMeta({ title: '我自己起的名字' }) })
    await expect(runSessionTitleNaming(h.ports)).resolves.toBe(false)

    expect(h.generations).toEqual([])
    expect(h.writes).toEqual([{ titleLockedAt: expect.any(Number) }])
    expect(h.meta().title).toBe('我自己起的名字')
    expect(h.logs.some(line => line.includes('human-named'))).toBe(true)
  })

  test('次数用尽：关闭窗口，不再消耗调用', async () => {
    const h = createHarness({
      meta: freshMeta({ title: '临时标题', titleAutoGeneratedAt: 1, titleRefineAttempts: TITLE_REFINE_MAX_ATTEMPTS }),
    })
    await expect(runSessionTitleNaming(h.ports)).resolves.toBe(false)
    expect(h.generations).toEqual([])
    expect(h.writes).toEqual([{ titleLockedAt: expect.any(Number) }])
  })

  test('无有效来源（寒暄 / 纯命令）：跳过且不消耗尝试次数', async () => {
    const h = createHarness({ messages: [userMessage('hi')], userMessage: '提交吧' })
    await expect(runSessionTitleNaming(h.ports)).resolves.toBe(false)
    expect(h.generations).toEqual([])
    expect(h.writes).toEqual([])
    expect(h.logs.some(line => line.includes('无信息量'))).toBe(true)
  })
})

describe('自动命名窗口：失败与并发语义', () => {
  test('生成器返回 null：算一次尝试，但不写标题、不投影、不抛错', async () => {
    const h = createHarness({ generate: async () => null })
    await expect(runSessionTitleNaming(h.ports)).resolves.toBe(false)
    expect(h.writes).toEqual([{ titleRefineAttempts: 1 }])
    expect(h.projected).toEqual([])
  })

  test('生成器抛错：被内部兜底吞掉，绝不外抛（失败不阻断本轮运行）', async () => {
    const h = createHarness({ generate: async () => { throw new Error('channel unavailable') } })
    await expect(runSessionTitleNaming(h.ports)).resolves.toBe(false)
    expect(h.projected).toEqual([])
    // 尝试次数已经预占（避免渠道不可用时每轮都烧一次请求）。
    expect(h.writes).toEqual([{ titleRefineAttempts: 1 }])
    expect(h.warns.some(line => line.includes('自动标题生成失败'))).toBe(true)
  })

  test('转录读取失败：退化为只用本轮消息，命名照常进行', async () => {
    const h = createHarness({ readMessagesThrows: true })
    await expect(runSessionTitleNaming(h.ports)).resolves.toBe(true)
    expect(h.generations[0]?.contextMessages).toEqual([USER_MESSAGE])
    expect(h.warns.some(line => line.includes('读取会话转录用于命名失败'))).toBe(true)
  })

  test('生成期间用户改名：丢弃本次结果，不覆盖、不投影', async () => {
    const h = createHarness({
      generate: async () => {
        // 模拟异步生成期间用户手动重命名。
        h.setMeta({ title: '用户改的名字' })
        return '模型标题'
      },
    })
    await expect(runSessionTitleNaming(h.ports)).resolves.toBe(false)
    expect(h.meta().title).toBe('用户改的名字')
    expect(h.projected).toEqual([])
    // 只有尝试次数那一笔写入。
    expect(h.writes).toEqual([{ titleRefineAttempts: 1 }])
  })

  test('生成期间外部定稿：同样丢弃结果', async () => {
    const h = createHarness({
      generate: async () => {
        h.setMeta({ titleLockedAt: Date.now() })
        return '模型标题'
      },
    })
    await expect(runSessionTitleNaming(h.ports)).resolves.toBe(false)
    expect(h.projected).toEqual([])
  })
})

describe('探索分支首次命名（继承「父标题 (fork)」的分支要有自己的名字）', () => {
  test('允许在非默认标题上命名一次，并标记分支标题已初始化', async () => {
    const h = createHarness({
      meta: freshMeta({
        title: '父会话标题 (fork)',
        explorationParentSessionId: 'parent-1',
        explorationSourceMessageId: 'anchor-1',
      }),
    })
    await expect(runSessionTitleNaming(h.ports)).resolves.toBe(true)
    expect(h.projected).toEqual(['生成标题·1'])
    // 尝试次数与分支初始化标记同期写入。
    expect(h.writes[0]).toEqual({ titleRefineAttempts: 1, explorationTitleInitializedAt: expect.any(Number) })
  })

  test('已初始化过的分支：按普通窗口语义处理（不再允许改写非默认标题）', async () => {
    const h = createHarness({
      meta: freshMeta({
        title: '父会话标题 (fork)',
        explorationParentSessionId: 'parent-1',
        explorationSourceMessageId: 'anchor-1',
        explorationTitleInitializedAt: 1,
      }),
    })
    await expect(runSessionTitleNaming(h.ports)).resolves.toBe(false)
    expect(h.generations).toEqual([])
    expect(h.writes).toEqual([{ titleLockedAt: expect.any(Number) }])
  })

  test('分叉锚点之后才算本分支来源（父会话历史不参与命名）', async () => {
    const forkMeta = freshMeta({
      explorationParentSessionId: 'parent-1',
      explorationSourceMessageId: 'anchor-1',
    })
    const sources = collectSessionTitleSources({
      sessionId: 'title-session',
      meta: forkMeta,
      fallbackMessage: '',
      logTag: '[test]',
      readMessages: () => [
        userMessage('父会话的首条消息（不应参与）'),
        assistantMessage('父会话的回复') as never,
        { type: 'assistant', uuid: 'anchor-1', message: { content: [{ type: 'text', text: '分叉点' }] }, parent_tool_use_id: null } as unknown as SDKMessage,
        userMessage('分支自己的诉求：比较两个模型的推理成本'),
      ],
    })
    expect(sources).toEqual(['分支自己的诉求：比较两个模型的推理成本'])
  })
})

describe('来源收集（共享实现，新链与旧链同一份）', () => {
  test('剥离注入块、跳过纯命令与寒暄、去重、并按上限截断', async () => {
    const sources = collectSessionTitleSources({
      sessionId: 'title-session',
      meta: freshMeta(),
      fallbackMessage: '兜底消息：整理一期迁移注意事项',
      logTag: '[test]',
      readMessages: () => [
        userMessage('<graph_focus>注入的图焦点块</graph_focus>\n真正的需求：重构标题模块'),
        userMessage('/compact'),
        userMessage('你好'),
        // 与第一条的有效文本相同（剥离注入块后）→ 去重。
        userMessage('真正的需求：重构标题模块'),
        userMessage('第二件事：把名字提取成共享模块'),
        userMessage('第三件事：补对照测试'),
        userMessage('第四件事：写验收要点'),
        userMessage('第五件事：更新交付目录'),
      ],
    })
    // 去重（第四条与第一条剥离注入块后的有效文本相同）+ 只取最早的 TITLE_SOURCE_MAX_COUNT 条
    // + 兜底消息排在最后（前四条已占满上限，因此兜底不参与）。
    expect(sources).toEqual([
      '真正的需求：重构标题模块',
      '第二件事：把名字提取成共享模块',
      '第三件事：补对照测试',
      '第四件事：写验收要点',
    ])
    expect(sources).toHaveLength(TITLE_SOURCE_MAX_COUNT)
    expect(sources).not.toContain('兜底消息：整理一期迁移注意事项')
  })

  test('只有寒暄/命令没有有效来源时，兜底消息成为唯一来源', async () => {
    const sources = collectSessionTitleSources({
      sessionId: 'title-session',
      meta: freshMeta(),
      fallbackMessage: '把发布流程拆成两步',
      logTag: '[test]',
      readMessages: () => [userMessage('hi'), userMessage('/help')],
    })
    expect(sources).toEqual(['把发布流程拆成两步'])
  })
})
